#!/usr/bin/env node
// PreToolUse(Edit|Write|MultiEdit): protect generated/frozen files, stop secrets, require a migration branch.
import fs from 'node:fs';
import path from 'node:path';
import { readInput, block, rel, branch, ROOT, SECRET_RES } from './_lib.mjs';

const ti = readInput().tool_input || {};
const r = rel(ti.file_path || ti.path || '');
if (!r) process.exit(0);

const PROTECTED = [
  [/^\.git\//, 'never edit .git internals'],
  [/^node_modules\//, 'never edit node_modules; change package versions instead'],
  [/^(build|dist)\//, 'build output is generated; never hand-edit'],
  [/^package-lock\.json$/, 'package-lock.json is generated by npm. Edit package.json / run npm install instead'],
  [/^\.claude\/(hooks\/|settings\.json$)/, 'the guard rails cannot be edited by the agent; ask the owner'],
];
for (const [re, why] of PROTECTED) if (re.test(r)) block(`${r}: ${why}.`);

if (r.startsWith('docs/migration/baseline/') && fs.existsSync(path.join(ROOT, r)))
  block(`${r}: the recorded baseline is frozen. Capture a new one only if the owner asks.`);

// secrets: scan only the text being written
const text = ti.content ?? ti.new_string ?? (Array.isArray(ti.edits) ? ti.edits.map((e) => e.new_string).join('\n') : '');
if (SECRET_RES.some((re) => re.test(text || '')))
  block('this change writes a literal API key. Read it from an env var (VITE_TMDB_API_KEY) instead and keep real values out of the repo.');

// branch guard: product code only on a migration branch
const SAFE_ON_MAIN = ['.claude/', 'docs/', 'CLAUDE.md', 'scripts/migration/', '.gitignore'];
const b = branch();
if (['main', 'master'].includes(b) && !SAFE_ON_MAIN.some((p) => r.startsWith(p)))
  block(`you are on "${b}". Run: git checkout -b migration/modernize  (then retry).`);
process.exit(0);
